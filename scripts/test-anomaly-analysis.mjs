import assert from "node:assert/strict";
import { buildLayerDrilldowns, buildMissingCollaborationNotices, createCollaborationNotice, detectEffectInversion, findEffectInversionEvent, isCollaborationNoticeEligible, projectCandidateVerification, scanRunningExperiments } from "../src/anomaly-analysis.mjs";

const event = findEffectInversionEvent("EXP-240611-017", "14d");
assert.ok(event);
assert.equal(detectEffectInversion(event, 0.28, "up").detected, true);
const zhaoCriticalEvent = findEffectInversionEvent("EXP-260901-101", "14d");
assert.ok(zhaoCriticalEvent);
assert.equal(detectEffectInversion(zhaoCriticalEvent, 0.3, "up").severity, "critical");
const zhaoWarningEvent = findEffectInversionEvent("EXP-260902-102", "14d");
assert.ok(zhaoWarningEvent);
assert.equal(detectEffectInversion(zhaoWarningEvent, 0.42, "up").detected, true);
assert.equal(findEffectInversionEvent("EXP-260903-103", "14d"), null);
const wuyaEvent = findEffectInversionEvent("EXP-240615-022", "14d");
assert.ok(wuyaEvent);
assert.equal(detectEffectInversion(wuyaEvent, 0.42, "up").detected, true);
assert.equal(detectEffectInversion(null, 0.42, "up").reason, "当前范围未定位异常");
assert.equal(detectEffectInversion({ ...event, pValue: 0.08 }, 0.28, "up").detected, false);
assert.equal(detectEffectInversion({ ...event, consecutiveWindows: 1 }, 0.28, "up").detected, false);
const target = { id: "EXP-240611-017", status: "running" };
const candidates = scanRunningExperiments(target, [target, { id: "EXP-240610-001", status: "running", owner: "赵晨" }, { id: "EXP-240615-022", status: "running", owner: "吴雅" }], [{ sourceExperimentId: target.id, targetExperimentId: "EXP-240610-001" }, { sourceExperimentId: target.id, targetExperimentId: "EXP-240615-022" }]);
assert.equal(candidates[0].experimentId, "EXP-240610-001");
assert.equal(candidates[0].status, "high_confidence");
assert.equal(projectCandidateVerification(candidates[0], { id: candidates[0].experimentId, name: "受限实验", owner: "赵晨" }, false).disclosure, "identified");
const restrictedCandidate = projectCandidateVerification(candidates[1], { id: candidates[1].experimentId, name: "受限实验", owner: "吴雅" }, false);
assert.equal(restrictedCandidate.disclosure, "identified");
assert.equal(restrictedCandidate.displayName, candidates[1].experimentId);
assert.equal(restrictedCandidate.owner, "吴雅");
assert.equal(restrictedCandidate.strategy, undefined);
assert.equal(restrictedCandidate.metric, undefined);
assert.equal(restrictedCandidate.rollout, undefined);
assert.equal(projectCandidateVerification(candidates[0], { id: candidates[0].experimentId, name: "可见实验", owner: "赵晨", trafficLayer: "x", userGroup: "u", coreMetric: "m", rollout: 30 }, true).disclosure, "full");
assert.equal(buildLayerDrilldowns()[0].contribution, 42);
assert.equal(isCollaborationNoticeEligible(candidates[0]), true);
assert.equal(isCollaborationNoticeEligible(candidates[1]), true);
assert.equal(createCollaborationNotice({ caseId: "CASE-1", verification: candidates[0], targetExperimentId: target.id, createdAt: "2026-10-29 10:00" }).text, "您负责的实验可能影响另一实验，已自动定位，建议关注。");
assert.equal(createCollaborationNotice({ caseId: "CASE-1", verification: candidates[1], targetExperimentId: target.id, createdAt: "2026-10-29 10:00" }).text, "您负责的实验与另一实验存在待核验交叉信号，请关注。");
const backfilled = buildMissingCollaborationNotices([{ id: "CASE-1", experimentId: target.id, updatedAt: "2026-10-29 10:00", verifications: candidates }], []);
assert.equal(backfilled.length, 2);
assert.equal(buildMissingCollaborationNotices([{ id: "CASE-1", experimentId: target.id, updatedAt: "2026-10-29 10:00", verifications: candidates }], backfilled).length, 0);
console.log("Anomaly-analysis tests passed.");
